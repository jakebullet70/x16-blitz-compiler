CommandREM: 
		jsr 	DCKeepMarker 				; pass zero: a dead-code keep marker (main/deadcode.asm)
_CRNext:
		jsr 	LookNext
		beq 	_CRExit
		jsr 	GetNext
		bra 	_CRNext
_CRExit:		
		rts

